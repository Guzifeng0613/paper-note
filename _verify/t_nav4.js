const {chromium}=require('playwright');const path=require('path');
const EXE='/opt/vm/preinstall/ms-playwright/chromium_headless_shell-1169/chrome-linux/headless_shell';
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
(async()=>{
  const b=await chromium.launch({headless:true,executablePath:EXE});
  const ctx=await b.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'no-preference'});
  const page=await ctx.newPage();
  page.on('pageerror',e=>console.log('[pageerror]',e.message));
  await page.goto('file://'+path.resolve('index.html'));
  await page.waitForFunction(()=>window.__app);await sleep(400);
  await page.evaluate(()=>location.hash='#/home');await sleep(300);
  page.evaluate(()=>location.hash='#/settings');
  await sleep(100);
  const st=await page.evaluate(()=>{const cs=getComputedStyle(document.querySelector('#scr-settings'));return {d:cs.transitionDuration,tr:cs.transform};});
  console.log('push@100ms:',JSON.stringify(st));
  await page.screenshot({path:'_verify/shots/nav_push_ok.png'});
  await sleep(350);
  await page.evaluate(()=>history.back());
  await sleep(100);
  await page.screenshot({path:'_verify/shots/nav_pop_ok.png'});
  await sleep(350);
  console.log('hash after back:',await page.evaluate(()=>location.hash));
  await b.close();
})();
